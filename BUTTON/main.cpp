/*
 * ПОЧЕМУ НУЖЕН АНТИДРЕБЕЗГ?
 * 
 * Механическая кнопка при нажатии не переключается мгновенно и идеально.
 * В течение нескольких миллисекунд контакты "дребезжат" - многократно
 * замыкаются и размыкаются. Без антидребезга программа увидит это как
 * несколько нажатий вместо одного.
 * 
 * ЧТО ТАКОЕ ВНУТРЕННЯЯ ПОДТЯЖКА (INPUT_PULLUP)?
 * 
 * У ESP32 внутри микросхемы есть резисторы, которые можно подключить к пину.
 * Если пин настроен как INPUT_PULLUP, он подтянут к 3.3V через резистор ~50 кОм.
 * Это избавляет от необходимости добавлять внешний резистор.
 * 
 * ПОЧЕМУ ПРИ НАЖАТИИ МЫ ПОЛУЧАЕМ LOW, А НЕ HIGH?
 * 
 * Это называется "активный уровень LOW". Кнопка замыкает пин на GND (0V).
 * Так сделано исторически, потому что:
 * 1. LOW уровень более устойчив к помехам
 * 2. Внутренняя подтяжка к 3.3V проще реализована аппаратно
 * 3. Большинство микроконтроллеров так устроены
 * 
 * ЧТО ДЕЛАТЬ, ЕСЛИ НУЖНА КНОПКА С АКТИВНЫМ УРОВНЕМ HIGH?
 * 
 * Нужно подключить кнопку между пином и 3.3V, а пин настроить как INPUT_PULLDOWN.
 * Но не все ESP32 пины поддерживают PULLDOWN, поэтому чаще используют LOW.
 * 
 * ============================================================================
 * КОНФИГУРАЦИЯ platformio.ini ДЛЯ ЭТОГО ПРОЕКТА
 * ============================================================================
 * 
 * [env:freenove_esp32_s3_wroom]
 * platform = espressif32
 * board = freenove_esp32_s3_wroom
 * framework = arduino
 * 
 * ; НАСТРОЙКИ ПАМЯТИ (16MB Flash + 8MB PSRAM)
 * board_build.flash_size = 16MB
 * board_build.psram = enabled
 * board_build.psram_mode = octal
 * board_build.arduino.memory_type = qio_opi
 * board_build.f_cpu = 240000000L
 * 
 * ; НАСТРОЙКИ ПОРТА
 * monitor_speed = 115200
 * upload_speed = 921600
 * monitor_filters = esp32_exception_decoder
 * 
 * ; БИБЛИОТЕКИ (не забудьте установить!)
 * lib_deps = 
 *     adafruit/Adafruit GFX Library@^1.12.6
 *     adafruit/Adafruit SSD1306@^2.5.16
 * 
 * ============================================================================
 */